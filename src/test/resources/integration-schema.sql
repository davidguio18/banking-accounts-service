DROP TABLE IF EXISTS accounts.movimientos;
DROP TABLE IF EXISTS accounts.cuentas;

CREATE TABLE accounts.cuentas (
    cuenta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_cuenta VARCHAR(30) NOT NULL UNIQUE,
    tipo_cuenta VARCHAR(20) NOT NULL,
    cliente_id BIGINT NOT NULL,
    saldo_inicial NUMERIC(18, 2) NOT NULL DEFAULT 0,
    saldo_actual NUMERIC(18, 2) NOT NULL DEFAULT 0,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT cuentas_tipo_check CHECK (tipo_cuenta IN ('AHORROS', 'CORRIENTE')),
    CONSTRAINT cuentas_saldo_inicial_check CHECK (saldo_inicial >= 0),
    CONSTRAINT cuentas_saldo_actual_check CHECK (saldo_actual >= 0)
);

CREATE TABLE accounts.movimientos (
    movimiento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id BIGINT NOT NULL REFERENCES accounts.cuentas(cuenta_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_movimiento VARCHAR(20) NOT NULL,
    valor NUMERIC(18, 2) NOT NULL,
    saldo NUMERIC(18, 2) NOT NULL,
    descripcion VARCHAR(250),
    CONSTRAINT movimientos_tipo_check CHECK (tipo_movimiento IN ('DEPOSITO', 'RETIRO')),
    CONSTRAINT movimientos_valor_check CHECK (
        valor <> 0 AND
        ((tipo_movimiento = 'DEPOSITO' AND valor > 0) OR
         (tipo_movimiento = 'RETIRO' AND valor < 0))
    ),
    CONSTRAINT movimientos_saldo_check CHECK (saldo >= 0)
);
